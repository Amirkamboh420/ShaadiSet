async function main() {
  console.log('📝 Adding more blog posts...')

  let added = 0
  for (const post of MORE_BLOG_POSTS) {
    const existing = await db.blogPost.findUnique({ where: { slug: post.slug } })
    if (existing) {
      console.log(`  ⏭  ${post.slug} exists`)
      continue
    }
    await db.blogPost.create({
      data: {
        title: post.title,
        slug: post.slug,
        excerpt: post.excerpt,
        content: post.content,
        category: post.category,
        author: post.author,
        imageUrl: post.imageUrl,
        published: true,
      },
    })
    added++
  }
  console.log(`✓ Added ${added} new blog posts`)
  console.log(`Total blog posts: ${await db.blogPost.count()}`)
}

main()
  .catch((e) => { console.error('Error:', e); process.exit(1) })
  .finally(async () => { await db.$disconnect() })
